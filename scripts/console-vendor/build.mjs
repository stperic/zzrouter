import { build } from 'esbuild';
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const source = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(source, '../../internal/server/web/console/vendor');
await mkdir(target, { recursive: true });
const chat = await build({
  absWorkingDir: source, entryPoints: ['../../internal/server/web/chat/chat.tsx'], outfile: path.join(target, 'chat.mjs'),
  nodePaths: [path.join(source, 'node_modules')], jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' },
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, metafile: true,
  legalComments: 'none', banner: { js: '// Generated by scripts/console-vendor/build.mjs. See THIRD_PARTY_NOTICES.txt.' },
  plugins: [{ name: 'shared-chat-transport', setup(build) {
    build.onResolve({ filter: /^\.\/transport$/ }, () => ({ path: './chat-transport.mjs', external: true }));
  } }],
});
const transport = await build({
  absWorkingDir: source, entryPoints: ['../../internal/server/web/chat/transport.ts'], outfile: path.join(target, 'chat-transport.mjs'),
  nodePaths: [path.join(source, 'node_modules')], bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  metafile: true, legalComments: 'none', banner: { js: '// Generated by scripts/console-vendor/build.mjs. See THIRD_PARTY_NOTICES.txt.' },
});
const discoveryMarkdown = await build({
  absWorkingDir: source, entryPoints: ['discovery-markdown.mjs'], outfile: path.join(target, 'discovery-markdown.mjs'),
  // Reuse the parser's DOM-free character decoder in the browser and Node tests.
  bundle: true, format: 'esm', platform: 'browser', conditions: ['worker'], target: 'es2022', minify: true,
  metafile: true, legalComments: 'none', banner: { js: '// Generated by scripts/console-vendor/build.mjs. See THIRD_PARTY_NOTICES.txt.' },
});
await build({
  absWorkingDir: source, entryPoints: ['events.mjs'], outfile: path.join(target, 'events.mjs'),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'none', banner: { js: '// Generated by scripts/console-vendor/build.mjs. See THIRD_PARTY_NOTICES.txt.' },
});
await build({
  absWorkingDir: source, entryPoints: ['entry.mjs'], outfile: path.join(target, 'graph.mjs'),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'eof', external: ['web-worker', './elk-worker.min.js'],
  banner: { js: '// Generated by scripts/console-vendor/build.mjs. See THIRD_PARTY_NOTICES.txt.' },
});
await copyFile(path.join(source, 'node_modules/elkjs/lib/elk-worker.min.js'), path.join(target, 'elk-worker.min.js'));
// Only the shipped provider marks enter the binary. Normalize monochrome SVGs
// for external-image rendering; their upstream geometry is unchanged.
for (const name of ['openai', 'anthropic', 'azure', 'bedrock', 'cloudflare', 'gemini', 'groq', 'openrouter', 'ollama', 'comfyui', 'vllm', 'huggingface']) {
  const svg = await readFile(path.join(source, `node_modules/@lobehub/icons-static-svg/icons/${name}.svg`), 'utf8');
  await writeFile(path.join(target, `../icons/provider-${name}.svg`), svg
    .replace('width="1em"', 'width="32"').replace('height="1em"', 'height="32"')
    .replaceAll('currentColor', '#89847c').replace(/ style="[^"]*"/g, '') + '\n');
}
const notices = [
  'Cytoscape.js 3.35.0: MIT, https://github.com/cytoscape/cytoscape.js/tree/v3.35.0',
  'ELK.js 0.12.1: distributed under EPL-2.0, https://github.com/kieler/elkjs/tree/v0.12.1',
  'ELK.js is unmodified. Corresponding source: https://github.com/kieler/elkjs and https://github.com/eclipse-elk/elk',
  'Lobe Icons static SVG 1.102.0: MIT, https://github.com/lobehub/lobe-icons/tree/989535d6c13da2dec5a2937fe2789d4af4fdd8e0',
  'Selected Lobe Icons use fixed dimensions and monochrome color. Logos identify their respective providers; no endorsement is implied.',
  '',
  await readFile(path.join(source, 'node_modules/cytoscape/LICENSE'), 'utf8'),
  await readFile(path.join(source, 'node_modules/elkjs/LICENSE.md'), 'utf8'),
  await readFile(path.join(source, 'licenses/lobehub.txt'), 'utf8'),
];
const packages = new Set([...Object.keys(chat.metafile.inputs), ...Object.keys(transport.metafile.inputs), ...Object.keys(discoveryMarkdown.metafile.inputs)].map(file => file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean));
for (const name of [...packages].sort()) {
  const directory = path.join(source, 'node_modules', name);
  const info = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  const license = (await readdir(directory)).find(file => /^licen[sc]e(?:\.|$)/i.test(file));
  // AI SDK's provider-utils package omits the monorepo's Apache license file.
  const omitted = { '@ai-sdk/provider-utils': '../node_modules/ai/LICENSE', 'react-remove-scroll-bar': 'react-remove-scroll-bar.txt', 'use-composed-ref': 'use-composed-ref.txt' };
  const licensePath = license ? path.join(directory, license) : omitted[name] ? path.join(source, 'licenses', omitted[name]) : null;
  if (!licensePath) throw new Error(`Missing license for bundled package ${name}`);
  notices.push(`${name} ${info.version}: ${info.license}\n${await readFile(licensePath, 'utf8')}`);
}
await writeFile(path.join(target, 'THIRD_PARTY_NOTICES.txt'), notices.join('\n\n').replaceAll('\r\n', '\n'));
