import { build } from 'esbuild';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const source = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(source, '../../internal/server/web/console/vendor');
await mkdir(target, { recursive: true });
await build({
  absWorkingDir: source, entryPoints: ['entry.mjs'], outfile: path.join(target, 'graph.mjs'),
  bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true,
  legalComments: 'eof', external: ['web-worker', './elk-worker.min.js'],
  banner: { js: '// Generated by scripts/console-vendor/build.mjs. See THIRD_PARTY_NOTICES.txt.' },
});
await copyFile(path.join(source, 'node_modules/elkjs/lib/elk-worker.min.js'), path.join(target, 'elk-worker.min.js'));
// Only the shipped provider marks enter the binary. Normalize monochrome SVGs
// for external-image rendering; their upstream geometry is unchanged.
for (const name of ['openai', 'anthropic', 'azure', 'bedrock', 'cloudflare', 'gemini', 'groq', 'openrouter', 'ollama', 'comfyui', 'vllm', 'huggingface']) {
  const svg = await readFile(path.join(source, `node_modules/@lobehub/icons-static-svg/icons/${name}.svg`), 'utf8');
  await writeFile(path.join(target, `../icons/provider-${name}.svg`), svg
    .replace('width="1em"', 'width="32"').replace('height="1em"', 'height="32"')
    .replaceAll('currentColor', '#52635b').replace(/ style="[^"]*"/g, '') + '\n');
}
